"""Coarse watermark mask generation.

Training: the ILAW masks are generated by applying random dilation/erosion to
the precise alpha mask (see ``generate.py``).

Evaluation: the "coarser mask" protocol applies ``perturb_seg`` to the mask
used at inference time (Table 1, lower section).
"""
import cv2
import numpy as np


def get_random_structure(size):
    choice = np.random.randint(1, 5)
    if choice == 1:
        return cv2.getStructuringElement(cv2.MORPH_RECT, (size, size))
    if choice == 2:
        return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (size, size))
    if choice == 3:
        return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (size, size // 2))
    return cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (size // 2, size))


def random_dilate(seg, min_size=3, max_size=5):
    size = np.random.randint(min_size, max_size)
    kernel = get_random_structure(size)
    return cv2.dilate(seg, kernel, iterations=1)


def random_erode(seg, min_size=3, max_size=5):
    size = np.random.randint(min_size, max_size)
    kernel = get_random_structure(size)
    return cv2.erode(seg, kernel, iterations=1)


def compute_iou(seg, gt):
    intersection = seg * gt
    union = seg + gt
    return (np.count_nonzero(intersection) + 1e-6) / (np.count_nonzero(union) + 1e-6)


def perturb_seg(gt, iou_target=0.85, max_iters=250):
    """Randomly dilate a binary mask until IoU with the original drops below
    ``iou_target``.  ``gt`` is a 2-D array with values in {0, 1} or {0, 255}.
    """
    h, w = gt.shape
    seg = gt.copy()
    _, seg = cv2.threshold(seg, 0, 255, 0)
    if h <= 2 or w <= 2:
        return seg

    for _ in range(max_iters):
        for _ in range(4):
            lx, ly = np.random.randint(w), np.random.randint(h)
            lw, lh = np.random.randint(lx + 1, w + 1), np.random.randint(ly + 1, h + 1)
            seg[ly:lh, lx:lw] = random_dilate(seg[ly:lh, lx:lw])
        if compute_iou(seg, gt) < iou_target:
            break
    return seg


def modify_boundary(image, iou_target=0.8):
    """Backward-compatible wrapper used by the data generation script."""
    image_ori = image.copy()
    image = perturb_seg(image, iou_target)
    is_shrinked = np.sum(np.where((np.where(image_ori == 1, 1, 0) +
                                   np.where(image == 0, 1, 0)) == 2, 1, 0)) > 0
    return image, is_shrinked
